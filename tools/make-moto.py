#!/usr/bin/env python3
"""Build moto.html (Erika Moto) from gp.html (Erika Racing).

Erika Moto is its own game on the game chooser, with its own access codes and its own saves, but it runs on the Erika
Racing engine: gp.html holds the shared code, and its `MOTO` switches give the bikes-only menus. After changing gp.html,
run this again from the repository root:

    python3 tools/make-moto.py
"""
import pathlib, sys

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / 'gp.html').read_text(encoding='utf-8')

def swap(text, old, new, count=None):
    n = text.count(old)
    if n == 0 or (count is not None and n != count):
        sys.exit(f'make-moto: expected {count or "some"} of {old!r} in gp.html, found {n}')
    return text.replace(old, new)

out = src
out = swap(out, "<script>window.ERIKA_GAME = 'race';   // Erika Racing needs a racing code</script>",
           "<script>window.ERIKA_GAME = 'moto'; window.ERIKA_MOTO = true;   // Erika Moto: the Grand Prix bikes, with their own codes</script>", 1)
out = swap(out, '<title>Erika Racing</title>', '<title>Erika Moto</title>', 1)
out = swap(out, '<span class="lg">RACING</span>', '<span class="lg">MOTO</span>')
out = swap(out, '<h1>ERIKA <span>RACING</span></h1>', '<h1>ERIKA <span>MOTO</span></h1>', 1)
# its own saves, settings and best laps, apart from Erika Racing's (same website, so the browser storage is shared)
out = swap(out, "'cargame.v2.", "'erikamoto.v1.")
out = swap(out, '`cargame.v2.', '`erikamoto.v1.')
out = out.replace('erikaracing.', 'erikamoto.')
out = out.replace('ERIKA RACING', 'ERIKA MOTO').replace('CIRCUIT SIMULATOR', 'GRAND PRIX BIKES').replace('Erika Racing', 'Erika Moto')
banner = ('<!-- Erika Moto: GENERATED from gp.html by tools/make-moto.py. Do not edit this file; edit gp.html and run the script. -->\n')
out = out.replace('<!doctype html>\n', '<!doctype html>\n' + banner, 1)
(root / 'moto.html').write_text(out, encoding='utf-8')
print('moto.html written,', len(out), 'bytes')
